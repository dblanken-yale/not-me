#!/usr/bin/env python3
"""Generate docs/cli.md and scripts/known-commands.txt from the notme.cli command registry.

    python3 scripts/gen-cli-docs.py           write both files
    python3 scripts/gen-cli-docs.py --check   exit 1 if either file is out of date
"""
import argparse
import inspect
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLUGIN = ROOT / "plugins" / "not-me"
DOC = ROOT / "docs" / "cli.md"
KNOWN = ROOT / "scripts" / "known-commands.txt"

sys.path.insert(0, str(PLUGIN))
from notme import cli  # noqa: E402


def _visible_actions(parser):
    """The leaf's own arguments: no help, no subparsers, no global flags, no --log (said once per write command)."""
    for a in parser._actions:
        if isinstance(a, (argparse._SubParsersAction, argparse._HelpAction)) or a.dest in cli.GLOBAL_DESTS:
            continue
        if a.dest == "log" and a.option_strings == ["--log"]:
            continue
        yield a


def _required(a):
    return a.required or (not a.option_strings and a.nargs not in ("?", "*"))


def option_rows(parser):
    rows = []
    for a in _visible_actions(parser):
        name = ", ".join(a.option_strings) if a.option_strings else (a.metavar or a.dest)
        if a.option_strings and a.nargs != 0:
            name += f" {a.metavar or a.dest.upper()}"
        if a.choices and not a.metavar:
            name += " {" + "|".join(str(c) for c in a.choices) + "}"
        note = (a.help or "").strip()
        if a.option_strings and a.default not in (None, False, argparse.SUPPRESS) and not _required(a):
            note = (note + f" (default {a.default})").strip()
        rows.append((name, "required" if _required(a) else "optional", note))
    return rows


def usage_line(path, parser):
    parts = ["notme", *path]
    for a in _visible_actions(parser):
        if a.option_strings:
            flag = a.option_strings[-1] + (f" {a.metavar or a.dest.upper()}" if a.nargs != 0 else "")
            parts.append(flag if a.required else f"[{flag}]")
        else:
            parts.append(a.metavar or a.dest)
    return " ".join(parts)


def split_doc(handler):
    text = inspect.getdoc(handler) or ""
    head, _, out = text.partition("Output:")
    return " ".join(head.split()), " ".join(out.split())


def intro():
    """The module docstring of notme.cli without its last paragraph (which is about this generator)."""
    paras = inspect.cleandoc(cli.__doc__).split("\n\n")
    return "\n\n".join(paras[1:-1]).replace("Contract\n    ", "```\n").replace(" ...\n\nstdout", " ...\n```\n\nstdout")


def render():
    leaves = cli.leaf_parsers(cli.build_parser())
    lines = ["# notme command line", "",
             "<!-- Generated by scripts/gen-cli-docs.py from the notme.cli command registry. Do not edit by hand. -->",
             "", intro(), "", "`--help` prints argparse text instead of JSON.", "", "## Global flags", "",
             "| Flag | Meaning |", "|------|---------|"]
    lines += [f"| `{flags[0]}` | {kw.get('help', '')} |" for flags, kw in cli.GLOBAL_FLAGS]
    lines += ["", "## Exit codes", "", "| Code | Meaning |", "|------|---------|"]
    lines += [f"| {int(code)} | {code.description} |" for code in cli.ExitCode]
    lines += ["", "## Commands", ""]
    for cmd in cli.COMMANDS:
        leaf = leaves[cmd.path]
        description, output = split_doc(cmd.handler)
        lines += [f"### `notme {cmd.name}`", "", description, "", "```", usage_line(cmd.path, leaf), "```", ""]
        rows = option_rows(leaf)
        if rows:
            lines += ["| Argument | Required | Meaning |", "|----------|----------|---------|"]
            lines += [f"| `{n}` | {r} | {note} |" for n, r, note in rows]
            lines.append("")
        if cmd.writes:
            lines += ["Writes to GitHub: honours `--dry-run`; takes `--log PATH`.", ""]
        lines += [f"Output: {output}" if output else "Output: see above.", ""]
    return "\n".join(lines).rstrip() + "\n"


def known():
    """Every leaf command (`me`, `log start`, `allow-repo add`, ...), one per line."""
    return "\n".join(cmd.name for cmd in cli.COMMANDS) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the generated files are out of date")
    args = ap.parse_args()
    wanted = {DOC: render(), KNOWN: known()}
    stale = [p for p, text in wanted.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"{p.relative_to(ROOT)} is out of date; run python3 scripts/gen-cli-docs.py", file=sys.stderr)
        return 1 if stale else 0
    for p, text in wanted.items():
        p.write_text(text, encoding="utf-8", newline="\n")
    print("wrote " + ", ".join(str(p.relative_to(ROOT)) for p in wanted))
    return 0


if __name__ == "__main__":
    sys.exit(main())
